import {readFileSync} from 'node:fs';import assert from 'node:assert/strict';
import {splitGames,summarize,comparisonRows,chartPoints,seasonsFor} from '../scripts/calculations.mjs';
const games=JSON.parse(readFileSync(new URL('../data/games.json',import.meta.url)));
const audit=JSON.parse(readFileSync(new URL('../data/validation.json',import.meta.url)));
assert.equal(games.length,125,'game count');assert.equal(new Set(games.map(g=>g.id)).size,125,'unique IDs');
assert(games.every(g=>g.date>='2018-12-18'&&g.date<='2026-10-19'&&Number.isInteger(g.pointsFor)&&Number.isInteger(g.pointsAgainst)),'dates and scores');
assert(games.every(g=>g.margin===g.pointsFor-g.pointsAgainst),'margins');
assert(games.every(g=>g.oneScore===(Math.abs(g.margin)<=8)),'one-score thresholds');
const {before,after}=splitGames(games);const a=summarize(before),b=summarize(after);
assert.deepEqual([a.games,a.wins,a.losses,b.games,b.wins,b.losses],[61,40,21,64,13,51]);
assert.equal(a.pf,1547);assert.equal(a.pa,1358);assert.equal(b.pf,1089);assert.equal(b.pa,1608);
assert.equal(a.playCoverage,61);assert.equal(b.playCoverage,63);
const eq=splitGames(games,'games');assert.equal(eq.before.length,eq.after.length);assert.equal(eq.before.length,61);
assert.equal(chartPoints(before).at(-1).y,a.wins);assert.equal(chartPoints(after).at(-1).y,b.wins);
assert.equal(seasonsFor(before,after).reduce((s,v)=>s+v.games.length,0),125);
assert.equal(comparisonRows(a,b).length,8);assert.equal(a.division.total>0,true);
assert.equal(games.find(g=>g.id==='2026-06-TEN-IND').pointsFor,26);
assert.equal(games.find(g=>g.id==='2026-06-TEN-IND').playDataAvailable,false);
assert.equal(audit.scoreCorrections.length,1);assert.equal(audit.issues.length,0);
console.log('PASS 19+ integrity assertions | 125 games | 61 before, 64 after | play coverage 124/125');
